    /**
     * A number with thousands separators in the page's language.
     *
     * @param int|float $number
     * @param bool $german
     * @return string
     */
    protected static function number( $number, $german )
    {
        return number_format( (float)$number, 0, $german ? ',' : '.', $german ? '.' : ',' );
    }

    /**
     * Speakers in millions as the page writes them.
     *
     * @param float|null $speakers
     * @param bool $german
     * @return string
     */
    protected static function speakers( $speakers, $german )
    {
        if ( $speakers === null )
            return '–';
        if ( $speakers < 1 )
            return $german ? '< 1' : '< 1';
        return self::number( round( $speakers ), $german );
    }

    /**
     * A work set as the page names it.
     *
     * @param array $wave
     * @param bool $german
     * @return string
     */
    protected function setLabel( array $wave, $german )
    {
        switch ( $wave['kind'] )
        {
            case 'admin':
                return ( $german ? 'Administration, Teil ' : 'Administration, part ' ) . $wave['set'];
            case 'review':
                return ( $german ? 'Administration, Teil ' . $wave['set'] . ' prüfen' : 'Administration, review part ' . $wave['set'] );
            case 'extensions':
                return $german ? 'Mitgelieferte Erweiterungen' : 'Shipped extensions';
            case 'setup':
                return $german ? 'Hilfe einrichten' : 'Set up the help';
            case 'locale':
                return $german ? 'Neue Locale' : 'New locale';
            case 'derived':
                $from = isset( self::DERIVED[$wave['locale']] ) ? self::DERIVED[$wave['locale']]['from'] : '';
                return ( $german ? 'Locale und Katalog aus ' : 'Locale and catalogue from ' ) . '`' . $from . '`';
        }
        return ( $german ? 'Hilfe ' : 'Help ' ) . '`' . $wave['set'] . '`';
    }

    /**
     * The size of a wave as the page writes it.
     *
     * @param array $wave
     * @param bool $german
     * @return string
     */
    protected static function sizeLabel( array $wave, $german )
    {
        $s = $wave['size'];
        switch ( $wave['kind'] )
        {
            case 'admin':
            case 'extensions':
                return self::number( $s['missing'], $german ) . ( $german ? ' von ' : ' of ' ) . self::number( $s['messages'], $german ) . ( $german ? ' Texten' : ' strings' );
            case 'review':
                return self::number( $s['messages'], $german ) . ( $german ? ' Texte' : ' strings' );
            case 'help':
                if ( $s['entries'] > 0 )
                    return self::number( $s['entries'], $german ) . ( $german ? ' Einträge, ' : ' entries, ' ) . self::number( $s['missing'], $german ) . ( $german ? ' Wörter' : ' words' );
                return self::number( $s['pages'], $german ) . ( $german ? ' Seiten, ' : ' pages, ' ) . self::number( $s['missing'], $german ) . ( $german ? ' Wörter' : ' words' );
        }
        return $german ? 'klein' : 'small';
    }

    /**
     * The prerequisites of a wave, short.
     *
     * @param array $wave
     * @param bool $german
     * @return string
     */
    protected function prerequisites( array $wave, $german )
    {
        $info = self::language( $wave['locale'] );
        $list = array();
        $guide = is_file( $this->root . '/share/translations/' . $wave['locale'] . '/GUIDE.md' );
        if ( !$guide && isset( self::DERIVED[$wave['locale']] ) )
            $list[] = $german ? 'Glossar der Abweichungen in `GUIDE.md`' : 'glossary of the differences in `GUIDE.md`';
        elseif ( !$guide )
            $list[] = $german ? '`GUIDE.md` zuerst' : '`GUIDE.md` first';
        else
            $list[] = '`GUIDE.md`';
        if ( $info['rtl'] )
            $list[] = 'RTL';
        if ( in_array( $wave['kind'], array( 'setup', 'help' ), true ) && !in_array( $info['script'], self::PDF_SCRIPTS, true ) )
            $list[] = $german ? 'PDF-Schrift ' . $info['script'] : 'PDF font ' . $info['script'];
        if ( $wave['kind'] === 'help' )
            $list[] = $german ? 'Wellen `S` und Administration' : 'waves `S` and administration';
        if ( in_array( $wave['kind'], array( 'admin', 'review' ), true ) && !is_file( $this->root . '/share/locale/' . $wave['locale'] . '.ini' ) )
            $list[] = $german ? 'Welle `L`' : 'wave `L`';
        return implode( ', ', $list );
    }

