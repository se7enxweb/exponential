            $range = $part['first'] === $part['last'] ? '`' . $part['first'] . '`' : '`' . $part['first'] . '` … `' . $part['last'] . '`';
            $out[] = '| `' . $part['id'] . '` | ' . $part['tier'] . ' | ' . $count . ' | ' . $n( $part['words'] ) . ' | ' . self::cell( $range ) . ' |';
        }
        $out[] = '';
        $out[] = '</details>';
        $out[] = '';
        $out[] = $g ? '<details><summary>Die ' . count( $data['admin']['parts'] ) . ' Teile des Administrationskatalogs</summary>' : '<details><summary>The ' . count( $data['admin']['parts'] ) . ' parts of the administration catalogue</summary>';
        $out[] = '';
        $out[] = $g ? '| Teil | Texte | Wörter | Kontexte (erster … letzter) |' : '| Part | Strings | Words | Contexts (first … last) |';
        $out[] = '|---|---:|---:|---|';
        foreach ( $data['admin']['parts'] as $part )
            $out[] = '| `' . $part['id'] . '` | ' . $n( $part['messages'] ) . ' | ' . $n( $part['words'] ) . ' | `' . self::cell( $part['first'] ) . '` … `' . self::cell( $part['last'] ) . '` |';
        $out[] = '';
        $out[] = '</details>';
        $out[] = '';

        // languages without a translation
        $out[] = $g ? '### Sprachen ohne Übersetzung' : '### Languages without a translation';
        $out[] = '';
        $out[] = $g ? 'Die Sprachen der mitgelieferten Locales, die die Administration auf Englisch zeigt, die Sprachen, die auf einem Branch übersetzt werden, und Sprachen mit fünf Millionen Sprechern oder mehr, für die es noch keine Locale gibt (der Code ist ein Vorschlag). Sortiert nach Sprechern je Schwierigkeitspunkt.'
                    : 'The languages of the shipped locales that the administration shows in English, the ones being translated on a branch, and languages of five million speakers or more that have no locale yet (the code is a proposal). Sorted by speakers per point of difficulty.';
        $out[] = '';
        $out[] = $g ? '| Sprache | Code | Sprecher (Mio.) | Schrift | Richtung | Schwierigkeit | Stand |' : '| Language | Code | Speakers (millions) | Script | Direction | Difficulty | State |';
        $out[] = '|---|---|---:|---|---|:-:|---|';
        $firstWave = array();
        foreach ( $data['queue'] as $wave )
        {
            if ( !isset( $firstWave[$wave['locale']] ) )
                $firstWave[$wave['locale']] = $wave['number'];
        }
        foreach ( $data['untranslated'] as $locale => $entry )
        {
            if ( $entry['in_progress'] )
                $state = $g ? 'in Arbeit (Branch)' : 'in progress (branch)';
            elseif ( isset( $entry['from'] ) )
                $state = ( $g ? 'abgeleitet aus `' : 'derived from `' ) . $entry['from'] . '`, ' . ( $g ? 'Welle #' : 'wave #' ) . $firstWave[$locale];
            elseif ( $entry['new'] )
                $state = ( $g ? 'neue Locale, Welle #' : 'new locale, wave #' ) . $firstWave[$locale];
            else
                $state = ( $g ? 'Welle #' : 'wave #' ) . $firstWave[$locale];
            $out[] = '| ' . self::cell( $entry[$name] ) . ' | `' . $locale . '` | ' . self::speakers( $entry['speakers'], $g ) . ' | ' . $entry['script'] . ' | '
                     . ( $entry['rtl'] ? 'RTL' : 'LTR' ) . ' | ' . $entry['difficulty'] . ' | ' . $state . ' |';
        }
        $out[] = '';

        // the queue
        $out[] = $g ? '### Die Warteschlange: die ersten ' . self::QUEUE_SHOWN . ' Wellen' : '### The queue: the first ' . self::QUEUE_SHOWN . ' waves';
        $out[] = '';
        $phases = $g ? array( 1 => 'Kataloge der Prioritätsgruppe', 2 => 'Deutsch: Hilfe des Alltags', 3 => 'Hilfe des Alltags der Prioritätsgruppe',
                              4 => 'Neue Übersetzungen', 5 => 'Erweiterungen der übrigen Sprachen', 6 => 'Hilfe des Alltags der übrigen Sprachen',
                              7 => 'Übrige Hilfe der Prioritätsgruppe', 8 => 'Übrige Hilfe der übrigen Sprachen' )
                     : array( 1 => 'Catalogues of the priority group', 2 => 'German: daily-use help', 3 => 'Daily-use help of the priority group',
                              4 => 'New translations', 5 => 'Extensions of the other languages', 6 => 'Daily-use help of the other languages',
                              7 => 'Rest of the help of the priority group', 8 => 'Rest of the help of the other languages' );
        $counts = array();
        foreach ( $data['queue'] as $wave )
            $counts[$wave['phase']] = isset( $counts[$wave['phase']] ) ? $counts[$wave['phase']] + 1 : 1;
        $out[] = $g ? '| Phase | Wellen |' : '| Phase | Waves |';
        $out[] = '|---|---:|';
        foreach ( $phases as $phase => $label )
            $out[] = '| ' . $phase . '. ' . $label . ' | ' . $n( isset( $counts[$phase] ) ? $counts[$phase] : 0 ) . ' |';
        $out[] = '';
        $out[] = $g ? '| # | Welle | Sprache | Arbeitspaket | Umfang (offen) | Schwierigkeit | Voraussetzungen |' : '| # | Wave | Language | Work set | Size (left) | Difficulty | Prerequisites |';
        $out[] = '|---:|---|---|---|---|:-:|---|';
        foreach ( array_slice( $data['queue'], 0, self::QUEUE_SHOWN ) as $wave )
        {
            $info = self::language( $wave['locale'] );
            $out[] = '| ' . $wave['number'] . ' | `' . $wave['id'] . '` | ' . self::cell( $info[$name] ) . ' | ' . $this->setLabel( $wave, $g ) . ' | '
                     . self::sizeLabel( $wave, $g ) . ' | ' . $wave['difficulty'] . ' | ' . $this->prerequisites( $wave, $g ) . ' |';
        }
        $out[] = '';
        $out[] = $g ? 'Die ganze Warteschlange und die Seiten einer Welle: `./console exp:i18n waves --list`, `./console exp:i18n waves --wave=<Welle>`.'
                    : 'The whole queue and the pages of a wave: `./console exp:i18n waves --list`, `./console exp:i18n waves --wave=<wave>`.';
        $out[] = '';
        $out[] = $g ? 'Erzeugt mit `./console exp:i18n waves`; `./console exp:i18n waves --check` und der Test `expI18nTranslationWavesTest` schlagen fehl, sobald ein Prozentwert nicht mehr stimmt oder ein Umfang um mehr als ' . (int)( self::TOLERANCE * 100 ) . ' % abweicht.'
                    : 'Made by `./console exp:i18n waves`; `./console exp:i18n waves --check` and the test `expI18nTranslationWavesTest` fail when a percentage changed or a size is more than ' . (int)( self::TOLERANCE * 100 ) . ' % off.';
        $out[] = '<!-- exp:i18n waves data ' . json_encode( $this->figures(), JSON_UNESCAPED_SLASHES ) . ' -->';
        $out[] = self::END;
        return implode( "\n", $out );
    }

    /**
     * A number with thousands separators in the page's language (for the closures of block()).
     *
     * @param int|float $number
     * @param bool $german
     * @return string
     */
    public static function numberText( $number, $german )
    {
        return self::number( $number, $german );
    }

    /**
     * The page with the generated part in place of the old one, or below the first heading.
     *
     * @param string $page
     * @param string $block
     * @return string
     */
    public static function replaceBlock( $page, $block )
    {
        return self::replaceOwn( $page, $block );
    }

    /**
     * replaceBlock(): between the markers, else below the first heading, after any front matter.
     *
     * @param string $page
     * @param string $block
     * @return string
     */
    protected static function replaceOwn( $page, $block )
    {
        $page = (string)$page;
        $start = preg_match( self::START_PATTERN, $page, $m, PREG_OFFSET_CAPTURE ) ? $m[0][1] : false;
        $end = strpos( $page, self::END );
        if ( $start !== false && $end !== false && $end > $start )
            return substr( $page, 0, $start ) . $block . substr( $page, $end + strlen( self::END ) );
        if ( preg_match( '/^# .*\n\n/m', $page, $h, PREG_OFFSET_CAPTURE ) )
        {
            $at = $h[0][1] + strlen( $h[0][0] );
            return substr( $page, 0, $at ) . $block . "\n\n" . substr( $page, $at );
        }
        return $block . "\n\n" . $page;
    }

    /**
     * The date in a page's start marker, or null.
     *
     * @param string $page
     * @return string|null
     */
    public static function markerDate( $page )
    {
        return preg_match( self::START_PATTERN, (string)$page, $m ) ? $m[1] : null;
    }

    /**
     * The figures in a page's data comment, or null.
     *
     * @param string $page
     * @return array|null
     */
    public static function pageFigures( $page )
    {
        if ( !preg_match( self::DATA_PATTERN, (string)$page, $m ) )
            return null;
        $figures = json_decode( $m[1], true );
        return is_array( $figures ) ? $figures : null;
    }

    /**
     * What the pages should hold: path => content. A page keeps the date of its marker while its generated part is
     * otherwise unchanged; else it gets $date.
     *
     * @param string $date YYYY-MM-DD
     * @return array
     */
    public function build( $date )
    {
        $files = array();
        foreach ( self::PAGES as $language => $path )
        {
            $page = (string)@file_get_contents( $this->root . '/' . $path );
            $marked = self::markerDate( $page );
            $content = self::replaceOwn( $page, $this->block( $language, $date ) );
            if ( $marked !== null && self::replaceOwn( $page, $this->block( $language, $marked ) ) === $page )
                $content = $page;
            $files[$path] = $content;
        }
        return $files;
    }

    /**
     * The differences between the pages and the measured figures: a list of messages, empty when the pages are current.
     * A page whose generated part is exactly what build() makes is current; otherwise its data comment must hold the
     * same percentages, the same languages without a translation and sizes within TOLERANCE.
     *
     * @param string $date
     * @return string[]
     */
    public function check( $date )
    {
        $problems = array();
        $built = $this->build( $date );
        $figures = $this->figures();
        foreach ( self::PAGES as $language => $path )
        {
            $current = @file_get_contents( $this->root . '/' . $path );
            if ( $current === false )
            {
                $problems[] = "$path is missing: run ./console exp:i18n waves";
                continue;
            }
            if ( $current === $built[$path] )
                continue;
            $page = self::pageFigures( $current );
            if ( $page === null || self::markerDate( $current ) === null )
            {
                $problems[] = "$path has no generated plan: run ./console exp:i18n waves";
                continue;
            }
            foreach ( self::compareFigures( $page, $figures ) as $difference )
                $problems[] = "$path is out of date ($difference): run ./console exp:i18n waves";
        }
        return $problems;
    }

    /**
     * The differences between two figures(): percentages and languages exactly, sizes and the number of waves within
     * TOLERANCE.
     *
     * @param array $page
     * @param array $measured
     * @return string[]
     */
    public static function compareFigures( array $page, array $measured )
    {
        $differences = array();
        $pageStatus = isset( $page['status'] ) ? (array)$page['status'] : array();
        foreach ( $measured['status'] as $code => $values )
        {
            if ( !isset( $pageStatus[$code] ) )
                $differences[] = "$code is new";
            elseif ( array_values( (array)$pageStatus[$code] ) !== $values )
                $differences[] = "$code: " . implode( '/', (array)$pageStatus[$code] ) . ' is now ' . implode( '/', $values );
        }
        foreach ( array_diff( array_keys( $pageStatus ), array_keys( $measured['status'] ) ) as $code )
            $differences[] = "$code is gone";
        if ( !isset( $page['untranslated'] ) || $page['untranslated'] !== $measured['untranslated'] )
            $differences[] = 'the languages without a translation changed';
        $sizes = $measured['sizes'] + array( 'waves' => $measured['waves'] );
        $pageSizes = ( isset( $page['sizes'] ) ? (array)$page['sizes'] : array() ) + array( 'waves' => isset( $page['waves'] ) ? $page['waves'] : null );
        foreach ( $sizes as $key => $value )
        {
            $old = isset( $pageSizes[$key] ) ? $pageSizes[$key] : null;
            if ( $old === null || abs( $old - $value ) > max( 2, self::TOLERANCE * max( $old, $value ) ) )
                $differences[] = "$key " . ( $old === null ? '-' : $old ) . " is now $value";
        }
        return $differences;
    }

    /**
     * Writes the pages that changed.
     *
     * @param string $date
     * @return string[] the paths written
     */
    public function write( $date )
    {
        $written = array();
        foreach ( $this->build( $date ) as $path => $content )
        {
            $file = $this->root . '/' . $path;
            if ( @file_get_contents( $file ) === $content )
                continue;
            if ( !is_dir( dirname( $file ) ) )
                mkdir( dirname( $file ), 0777, true );
            file_put_contents( $file, $content );
            $written[] = $path;
        }
        return $written;
    }

    /**
     * One wave or one work set, for the command line: the pages (or contexts, table files, extensions) it covers and,
     * for a language, which of them are done.
     *
     * @param string $wave <locale>/<set> or a work set (A03, H-help-manual, X01, E)
     * @return array|null hash( locale, set, items => list of hash( item, done (bool|null) ) ), null when unknown
     */
    public function wave( $wave )
    {
        $wave = (string)$wave;
        $locale = '';
        $set = $wave;
        if ( strpos( $wave, '/' ) !== false )
            list( $locale, $set ) = explode( '/', $wave, 2 );
        $data = $this->data();
        $items = null;
        if ( $set === 'E' )
        {
            $items = array();
            foreach ( $data['extensions'] as $name => $messages )
            {
                $done = null;
                if ( $locale !== '' )
                    $done = is_file( $this->root . '/extension/' . $name . '/translations/' . $locale . '/translation.ts' );
                $items[] = array( 'item' => $name . ' (' . $messages . ')', 'done' => $done );
            }
        }
        foreach ( $data['admin']['parts'] as $part )
        {
            if ( $part['id'] === $set )
            {
                $items = array();
                foreach ( $part['contexts'] as $context )
                    $items[] = array( 'item' => $context, 'done' => null );
            }
        }
        foreach ( $data['help']['parts'] as $part )
        {
            if ( $part['id'] !== $set )
                continue;
            $items = array();
            $translated = array();
            if ( $locale !== '' && $part['tier'] !== 'tables' )
                $translated = $this->translatedPages( strtolower( $locale ), $this->pages() );
            foreach ( $part['items'] as $item )
                $items[] = array( 'item' => $item, 'done' => $locale === '' || $part['tier'] === 'tables' ? null : isset( $translated[$item] ) );
        }
        if ( $items === null )
            return null;
        return array( 'locale' => $locale, 'set' => $set, 'items' => $items );
    }
