/**
 * The translation waves: a measured plan to bring every language to daily use, at the top of
 * doc/eng-us/translation-waves.md and doc/ger-de/uebersetzungswellen.md (./console exp:i18n waves).
 *
 * It measures, from the files a release ships and without a database:
 *
 * - the administration catalogue of every translation (share/translations/<code>/translation.ts) against the source
 *   texts (share/translations/untranslated/translation.ts), message by message as the translator counts them
 *   (expUISwitchLanguageCatalogue::messageKeys(): context, source and comment, the whole text of a source that holds a
 *   Qt <byte value="..."/> element), and per part of it (the contexts in order, at most MAX_MESSAGES messages a part);
 * - the catalogues of the extensions the kernel ships (those whose untranslated catalogue share/filelist.md5 lists);
 * - the help: every page below doc/eng-us/ by section, its words (front matter and code blocks left out), the tier of
 *   its section (daily use, product and audience guides, developer reference) and, per documentation language below
 *   doc/, the pages it has translated (doc/<language>/.paths.json, or the same path); the pages generated by
 *   exp:help:examples count as the tables they are made from (doc/<language>/.examples/, measured against the German
 *   tables, the only complete set);
 * - the languages: speakers, script, direction, difficulty (static figures, see LANGUAGES), the languages the
 *   administration does not show translated yet, the ones being translated on a branch (IN_PROGRESS) and the
 *   languages that have no locale yet (NEW_LOCALES, DERIVED).
 *
 * From that it orders the waves: one language and one work set each (a part of the administration catalogue, the
 * shipped extension catalogues, the setup of a help language, a part of the help), small enough for one translator to
 * start and finish at any time, independently of the others. The generated part of each page lies between its START
 * and END markers and carries its figures as a data comment; check() fails when a percentage changed or when a size is
 * more than TOLERANCE away from the measured one, so that the plan cannot go stale silently, while an edit of a few
