    /** @var string the installation root, without a trailing slash */
    protected $root;

    /** @var array|null see data() */
    protected $data;

    /** @var expUISwitchLanguageCatalogue|null */
    protected $catalogue;

    /**
     * @param string $root the installation root
     */
    public function __construct( $root )
    {
        $this->root = rtrim( (string)$root, '/' );
    }

    /**
     * The catalogue reader of the interface language switch, which counts as the translator does.
     *
     * @return expUISwitchLanguageCatalogue
     */
    protected function catalogue()
    {
        if ( $this->catalogue === null )
            $this->catalogue = new expUISwitchLanguageCatalogue( $this->root, '' );
        return $this->catalogue;
    }

    /**
     * The words of a text: runs of letters and digits, an apostrophe or hyphen inside a word keeps it whole.
     *
     * @param string $text
     * @return int
     */
    public static function countWords( $text )
    {
        return (int)preg_match_all( '/[\p{L}\p{M}\p{N}]+(?:[\'’\-][\p{L}\p{M}\p{N}]+)*/u', (string)$text );
    }

    /**
     * The words of a Markdown page to translate: without its front matter and its fenced code blocks.
     *
     * @param string $text
     * @return int
     */
    public static function pageWords( $text )
    {
        $text = (string)preg_replace( '/\A---\n.*?\n---\n/s', '', str_replace( "\r\n", "\n", (string)$text ) );
        $text = (string)preg_replace( '/^(```|~~~)[^\n]*\n.*?^\1[ \t]*$/ms', '', $text );
        return self::countWords( $text );
    }

    /**
     * What is known of a locale (or a language code): code, language, en, de, speakers (millions or null), script,
     * rtl, morphology, terminology, difficulty (1 to 5) and score (speakers per point of difficulty).
     *
     * @param string $locale ara-SA, or a language code
     * @return array
     */
    public static function language( $locale )
    {
        $code = substr( (string)$locale, 0, 3 );
        $base = isset( self::LANGUAGES[$code] ) ? self::LANGUAGES[$code] : array( $locale, $locale, null, 'Latn', 0, 2 );
        $own = isset( self::LOCALES[$locale] ) ? self::LOCALES[$locale] : array();
        $derived = isset( self::DERIVED[$locale] ) ? self::DERIVED[$locale] : array();
        $info = array( 'code' => (string)$locale, 'language' => $code,
                       'en' => isset( $own['en'] ) ? $own['en'] : ( isset( $derived['en'] ) ? $derived['en'] : $base[0] ),
                       'de' => isset( $own['de'] ) ? $own['de'] : ( isset( $derived['de'] ) ? $derived['de'] : $base[1] ),
                       'speakers' => array_key_exists( 'speakers', $own ) ? $own['speakers'] : $base[2],
                       'script' => isset( $own['script'] ) ? $own['script'] : $base[3],
                       'morphology' => $base[4], 'terminology' => $base[5] );
        $info['rtl'] = in_array( $info['script'], self::RTL_SCRIPTS, true );
        $points = isset( self::SCRIPT_POINTS[$info['script']] ) ? self::SCRIPT_POINTS[$info['script']] : 2;
        $info['difficulty'] = max( 1, min( 5, 1 + $points + ( $info['rtl'] ? 1 : 0 ) + $info['morphology'] + $info['terminology'] ) );
        $info['score'] = $info['speakers'] === null ? 0.0 : $info['speakers'] / $info['difficulty'];
        return $info;
    }

    /**
     * The parts of the administration catalogue: the contexts of the source texts in their order, cut into parts of at
     * most MAX_MESSAGES messages. List of hash( id (A01 ...), contexts (names), first, last, messages, words, keys ).
     *
     * @return array
     */
    public function adminParts()
    {
        $keys = $this->catalogue()->messageKeys( $this->root . '/share/translations/untranslated/translation.ts', false );
        $contexts = array();
        foreach ( array_keys( $keys ) as $key )
        {
            $parts = explode( "\x1F", (string)$key, 3 );
            $name = $parts[0];
            if ( !isset( $contexts[$name] ) )
                $contexts[$name] = array( 'messages' => 0, 'words' => 0, 'keys' => array() );
            $contexts[$name]['messages']++;
            $contexts[$name]['words'] += self::countWords( isset( $parts[1] ) ? strip_tags( html_entity_decode( $parts[1], ENT_QUOTES | ENT_HTML5, 'UTF-8' ) ) : '' );
            $contexts[$name]['keys'][$key] = true;
        }
        $result = array();
        $current = null;
        foreach ( $contexts as $name => $context )
        {
            if ( $current !== null && $current['messages'] + $context['messages'] > self::MAX_MESSAGES )
            {
                $result[] = $current;
                $current = null;
            }
            if ( $current === null )
                $current = array( 'contexts' => array(), 'first' => $name, 'last' => $name, 'messages' => 0, 'words' => 0, 'keys' => array() );
            $current['contexts'][] = $name;
            $current['last'] = $name;
            $current['messages'] += $context['messages'];
            $current['words'] += $context['words'];
            $current['keys'] += $context['keys'];
        }
        if ( $current !== null )
            $result[] = $current;
        foreach ( $result as $i => $part )
            $result[$i] = array( 'id' => sprintf( 'A%02d', $i + 1 ) ) + $part;
        return $result;
    }

    /**
     * The extensions the kernel ships with a catalogue: those whose untranslated catalogue share/filelist.md5 lists and
     * that are here. name => translations directory, sorted.
     *
     * @return array
     */
    public function shippedExtensions()
    {
        $list = array();
        $manifest = (string)@file_get_contents( $this->root . '/share/filelist.md5' );
        if ( preg_match_all( '#^[0-9a-f]{32}\s+extension/([A-Za-z0-9_.-]+)/translations/untranslated/translation\.ts$#m', $manifest, $m ) )
        {
            foreach ( $m[1] as $name )
            {
                if ( is_file( $this->root . '/extension/' . $name . '/translations/untranslated/translation.ts' ) )
                    $list[$name] = $this->root . '/extension/' . $name . '/translations';
            }
        }
        ksort( $list, SORT_STRING );
        return $list;
    }

    /**
     * The section of a page below doc/eng-us/: help for help/<page>.md, help/<folder> below it, else the first
     * directory, root for a page directly below doc/eng-us/.
     *
     * @param string $id
     * @return string
     */
    public static function sectionOf( $id )
    {
        $parts = explode( '/', (string)$id );
        if ( count( $parts ) === 1 )
            return 'root';
        if ( $parts[0] === 'help' )
            return count( $parts ) === 2 ? 'help' : 'help/' . $parts[1];
        return $parts[0];
    }

    /**
     * The tier of a section: daily, guides or reference.
     *
     * @param string $section
     * @return string
     */
    public static function tierOf( $section )
    {
        if ( in_array( $section, self::DAILY_SECTIONS, true ) )
            return 'daily';
        if ( in_array( $section, self::REFERENCE_SECTIONS, true ) )
            return 'reference';
        return 'guides';
    }

    /**
     * Every Markdown file below a directory, relative paths sorted.
     *
     * @param string $dir
     * @return string[]
     */
    protected static function markdownFiles( $dir )
    {
        $list = array();
        if ( !is_dir( $dir ) )
            return $list;
        $iterator = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ) );
        foreach ( $iterator as $file )
        {
            if ( $file->isFile() && substr( $file->getFilename(), -3 ) === '.md' )
                $list[] = str_replace( '\\', '/', substr( $file->getPathname(), strlen( $dir ) + 1 ) );
        }
        sort( $list, SORT_STRING );
        return $list;
    }

    /**
     * The pages of the help: id => hash( section, tier, words ); pages made by exp:help:examples are left out (they are
     * the tables, see tables()).
     *
     * @return array
     */
    public function pages()
    {
        $pages = array();
        $dir = $this->root . '/doc/eng-us';
        // this plan's own page is left out: what it measures would change with every measurement
        $own = substr( self::PAGES['eng-us'], strlen( 'doc/eng-us/' ) );
        foreach ( self::markdownFiles( $dir ) as $id )
        {
            if ( $id === $own )
                continue;
            $text = (string)file_get_contents( $dir . '/' . $id );
            if ( preg_match( '/\A---\n(?:.*\n)*?generated: exp:help:examples\b/', str_replace( "\r\n", "\n", substr( $text, 0, 2048 ) ) ) )
                continue;
            $section = self::sectionOf( $id );
            $pages[$id] = array( 'section' => $section, 'tier' => self::tierOf( $section ), 'words' => self::pageWords( $text ) );
        }
        return $pages;
    }

    /**
     * The tables the generated reference examples are made from, measured on the German tables (doc/ger-de/.examples/):
     * file (strings.json, descriptions/<name>.json) => hash( entries, words, english (entry => English text) ).
     *
     * @return array
     */
    public function tables()
    {
        $tables = array();
        $dir = $this->root . '/doc/ger-de/' . expHelpExamplesTranslation::TABLE_DIR;
        $files = array();
        if ( is_file( $dir . '/strings.json' ) )
            $files[] = 'strings.json';
        foreach ( (array)glob( $dir . '/descriptions/*.json' ) as $file )
            $files[] = 'descriptions/' . basename( $file );
        sort( $files, SORT_STRING );
        foreach ( $files as $file )
        {
            $json = json_decode( (string)file_get_contents( $dir . '/' . $file ), true );
            if ( !is_array( $json ) )
                continue;
            $english = array();
            if ( $file === 'strings.json' )
            {
                foreach ( $json as $group => $entries )
                {
                    foreach ( (array)$entries as $source => $translated )
                        $english[$group . ':' . $source] = (string)$source;
                }
            }
            else
            {
                foreach ( $json as $key => $entry )
                {
                    if ( is_array( $entry ) && isset( $entry['en'] ) )
                        $english[(string)$key] = (string)$entry['en'];
                }
            }
            $words = 0;
            foreach ( $english as $text )
                $words += self::countWords( $text );
            $tables[$file] = array( 'entries' => count( $english ), 'words' => $words, 'english' => $english );
        }
        return $tables;
    }

    /**
     * The parts of the help: each section of a tier in its order, cut into parts of at most MAX_PAGES pages and
     * MAX_WORDS words (as even as the pages allow), and the tables in parts of at most MAX_WORDS words. List of hash( id,
     * tier, sections, items (page ids or table files), pages, entries, words, first, last ).
     *
     * @param array $pages pages()
     * @param array $tables tables()
     * @return array
     */
    public static function helpParts( array $pages, array $tables )
    {
        $bySection = array();
        foreach ( $pages as $id => $page )
            $bySection[$page['section']][$id] = $page['words'];
        $order = array_merge( self::DAILY_SECTIONS, array() );
        $guides = array();
        foreach ( array_keys( $bySection ) as $section )
        {
            if ( self::tierOf( $section ) === 'guides' )
                $guides[] = $section;
        }
        // install and features first, then the help's audience folders, the root pages last
        usort( $guides, function ( $a, $b )
        {
            $rank = function ( $s ) { return $s === 'install' ? 0 : ( $s === 'features' ? 1 : ( $s === 'root' ? 3 : 2 ) ); };
            return $rank( $a ) === $rank( $b ) ? strcmp( $a, $b ) : $rank( $a ) - $rank( $b );
        } );
        $order = array_merge( $order, $guides, self::REFERENCE_SECTIONS );
        $parts = array();
        foreach ( $order as $section )
        {
            if ( empty( $bySection[$section] ) )
                continue;
            $items = $bySection[$section];
            $ids = array_keys( $items );
            $count = count( $ids );
            $words = array_sum( $items );
            $n = max( 1, (int)ceil( $count / self::MAX_PAGES ), (int)ceil( $words / self::MAX_WORDS ) );
            $n = min( $n, $count );
            $slug = str_replace( '/', '-', $section );
            for ( $i = 0; $i < $n; $i++ )
            {
                $slice = array_slice( $ids, (int)floor( $i * $count / $n ), (int)floor( ( $i + 1 ) * $count / $n ) - (int)floor( $i * $count / $n ) );
                $sum = 0;
                foreach ( $slice as $id )
                    $sum += $items[$id];
                $parts[] = array( 'id' => 'H-' . $slug . ( $n > 1 ? sprintf( '-%02d', $i + 1 ) : '' ), 'tier' => self::tierOf( $section ),
                                  'sections' => array( $section ), 'items' => $slice, 'pages' => count( $slice ), 'entries' => 0,
                                  'words' => $sum, 'first' => $slice[0], 'last' => $slice[count( $slice ) - 1] );
            }
        }
        // the tables: whole files, in order, up to MAX_WORDS a part
        $current = null;
        $number = 0;
        $flush = function () use ( &$current, &$parts, &$number )
        {
            if ( $current === null )
                return;
            $number++;
            $current['id'] = sprintf( 'X%02d', $number );
            $current['first'] = $current['items'][0];
            $current['last'] = $current['items'][count( $current['items'] ) - 1];
            $parts[] = $current;
            $current = null;
        };
        foreach ( $tables as $file => $table )
        {
            if ( $current !== null && $current['words'] + $table['words'] > self::MAX_WORDS )
                $flush();
            if ( $current === null )
                $current = array( 'id' => '', 'tier' => 'tables', 'sections' => array( 'examples' ), 'items' => array(), 'pages' => 0,
                                  'entries' => 0, 'words' => 0, 'first' => '', 'last' => '' );
            $current['items'][] = $file;
            $current['entries'] += $table['entries'];
            $current['words'] += $table['words'];
        }
        $flush();
        return $parts;
    }

    /**
     * The documentation languages below doc/ other than the original: directory => true.
     *
     * @return array
     */
    public function docDirectories()
    {
        $list = array();
        foreach ( (array)glob( $this->root . '/doc/*', GLOB_ONLYDIR ) as $dir )
        {
            $name = basename( $dir );
            if ( $name !== 'eng-us' && preg_match( '#^[a-z]{3}-[a-z]{2,4}$#', $name ) )
                $list[$name] = true;
        }
        ksort( $list, SORT_STRING );
        return $list;
    }

    /**
     * The page ids a documentation language has translated: the targets of its .paths.json whose file exists, and the
     * files at the original's path. id => true.
     *
     * @param string $directory ger-de
     * @param array $pages pages()
     * @return array
     */
    public function translatedPages( $directory, array $pages )
    {
        $dir = $this->root . '/doc/' . $directory;
        $done = array();
        $map = json_decode( (string)@file_get_contents( $dir . '/.paths.json' ), true );
        if ( is_array( $map ) )
        {
            foreach ( $map as $translated => $id )
            {
                if ( is_string( $id ) && isset( $pages[$id] ) && is_file( $dir . '/' . $translated ) )
                    $done[$id] = true;
            }
        }
        foreach ( array_keys( $pages ) as $id )
        {
            if ( !isset( $done[$id] ) && is_file( $dir . '/' . $id ) )
                $done[$id] = true;
        }
        return $done;
    }

    /**
     * Per table file, the words of the entries a documentation language has translated.
     *
     * @param string $directory
     * @param array $tables tables()
     * @return array file => words
     */
    public function translatedTables( $directory, array $tables )
    {
        $result = array();
        $dir = $this->root . '/doc/' . $directory . '/' . expHelpExamplesTranslation::TABLE_DIR;
        $field = substr( $directory, 0, 3 ) === 'ger' ? 'de' : strtolower( (string)strtok( expHelpLanguage::htmlLang( $directory ), '-' ) );
        foreach ( $tables as $file => $table )
        {
            $result[$file] = 0;
            $json = json_decode( (string)@file_get_contents( $dir . '/' . $file ), true );
            if ( !is_array( $json ) )
                continue;
            foreach ( $table['english'] as $key => $english )
            {
                if ( $file === 'strings.json' )
                {
                    list( $group, $source ) = explode( ':', $key, 2 );
                    $ok = isset( $json[$group][$source] ) && trim( (string)$json[$group][$source] ) !== '';
                }
                else
                    $ok = isset( $json[$key][$field], $json[$key]['en'] ) && $json[$key]['en'] === $english && trim( (string)$json[$key][$field] ) !== '';
                if ( $ok )
                    $result[$file] += self::countWords( $english );
            }
        }
        return $result;
    }

    /**
     * A share in whole percent, rounded down; 100 for nothing to do.
     *
     * @param int|float $done
     * @param int|float $total
     * @return int
     */
    public static function percent( $done, $total )
    {
        return $total > 0 ? (int)min( 100, floor( $done * 100 / $total ) ) : 100;
    }

    /**
     * Everything the pages show:
     *   admin: hash( parts (adminParts() without keys), messages, words ),
     *   extensions: name => messages,
     *   help: hash( parts (helpParts() without items), tiers => hash( pages, words, parts ) ),
     *   status: locale => hash( admin, admin_parts (id => percent), extensions, daily, help, help_parts (id => percent
     *           of words), help_pages (translated pages), directory ),
     *   untranslated: languages without a translation of their own, list of hash( locale, in_progress ) and the
     *                 language() keys,
     *   queue: the waves in order (see queue()).
     *
     * @return array
     */
    public function data()
    {
        if ( $this->data !== null )
            return $this->data;
        $catalogue = $this->catalogue();
        $adminParts = $this->adminParts();
        $extensions = array();
        $extensionKeys = array();
        foreach ( $this->shippedExtensions() as $name => $dir )
        {
            $extensionKeys[$name] = $catalogue->messageKeys( $dir . '/untranslated/translation.ts', false );
            $extensions[$name] = count( $extensionKeys[$name] );
        }
        $pages = $this->pages();
        $tables = $this->tables();
        $helpParts = self::helpParts( $pages, $tables );
        $directories = $this->docDirectories();

        $codes = array();
        foreach ( (array)glob( $this->root . '/share/translations/*/translation.ts' ) as $file )
        {
            $code = basename( dirname( $file ) );
            if ( $code !== 'untranslated' )
                $codes[] = $code;
        }
        sort( $codes, SORT_STRING );

        $status = array();
        foreach ( $codes as $code )
        {
            $english = strpos( $code, 'eng-' ) === 0;
            $finished = $english ? array() : $catalogue->messageKeys( $this->root . '/share/translations/' . $code . '/translation.ts', true );
            $row = array( 'admin_parts' => array(), 'help_parts' => array() );
            $done = 0;
            $total = 0;
            foreach ( $adminParts as $part )
            {
                $have = $english ? $part['messages'] : count( array_intersect_key( $finished, $part['keys'] ) );
                $row['admin_parts'][$part['id']] = self::percent( $have, $part['messages'] );
                $done += $have;
                $total += $part['messages'];
            }
            $row['admin'] = self::percent( $done, $total );
            $done = 0;
            $total = 0;
            foreach ( $extensionKeys as $name => $keys )
            {
                $file = $this->root . '/extension/' . $name . '/translations/' . $code . '/translation.ts';
                $done += $english ? count( $keys ) : ( is_file( $file ) ? count( array_intersect_key( $catalogue->messageKeys( $file, true ), $keys ) ) : 0 );
                $total += count( $keys );
            }
            $row['extensions'] = self::percent( $done, $total );
            $directory = strtolower( $code );
            $row['directory'] = $english ? 'eng-us' : ( isset( $directories[$directory] ) ? $directory : '' );
            $translated = $row['directory'] !== '' && !$english ? $this->translatedPages( $directory, $pages ) : array();
            $tableWords = $row['directory'] !== '' && !$english ? $this->translatedTables( $directory, $tables ) : array();
            $dailyDone = $dailyTotal = $allDone = $allTotal = 0;
            $row['help_pages'] = $english ? count( $pages ) : count( $translated );
            foreach ( $helpParts as $part )
            {
                $have = 0;
                foreach ( $part['items'] as $item )
                {
                    if ( $part['tier'] === 'tables' )
                        $have += $english ? $tables[$item]['words'] : ( isset( $tableWords[$item] ) ? $tableWords[$item] : 0 );
                    elseif ( $english || isset( $translated[$item] ) )
                        $have += $pages[$item]['words'];
                }
                $row['help_parts'][$part['id']] = self::percent( $have, $part['words'] );
                $allDone += $have;
                $allTotal += $part['words'];
                if ( $part['tier'] === 'daily' )
                {
                    $dailyDone += $have;
                    $dailyTotal += $part['words'];
                }
            }
            $row['daily'] = self::percent( $dailyDone, $dailyTotal );
            $row['help'] = self::percent( $allDone, $allTotal );
            $status[$code] = $row;
        }

        // the languages of the locales without a translation of their own, and the ones without a locale
        $map = new expI18nCoverageMap( $this->root );
        $untranslated = array();
        foreach ( $map->untranslatedLanguages() as $language )
        {
            $locale = $language['locales'][0]['locale'];
            foreach ( $language['locales'] as $candidate )
            {
                if ( in_array( $candidate['locale'], self::IN_PROGRESS, true ) )
                    $locale = $candidate['locale'];
            }
            $untranslated[$locale] = array( 'locale' => $locale, 'new' => false );
        }
        foreach ( self::IN_PROGRESS as $locale )
        {
            if ( !isset( $status[$locale] ) && !isset( $untranslated[$locale] ) && !is_file( $this->root . '/share/locale/' . $locale . '.ini' ) )
                $untranslated[$locale] = array( 'locale' => $locale, 'new' => true );
        }
        foreach ( self::NEW_LOCALES as $locale )
        {
            if ( !isset( $status[$locale] ) && !is_file( $this->root . '/share/locale/' . $locale . '.ini' ) )
                $untranslated[$locale] = array( 'locale' => $locale, 'new' => true );
        }
        foreach ( self::DERIVED as $locale => $info )
        {
            if ( !isset( $status[$locale] ) && isset( $status[$info['from']] ) )
                $untranslated[$locale] = array( 'locale' => $locale, 'new' => !is_file( $this->root . '/share/locale/' . $locale . '.ini' ), 'from' => $info['from'] );
        }
        foreach ( $untranslated as $locale => $entry )
        {
            $entry['in_progress'] = in_array( $locale, self::IN_PROGRESS, true ) && !isset( $status[$locale] );
            $untranslated[$locale] = $entry + self::language( $locale );
        }
        uasort( $untranslated, function ( $a, $b )
        {
            if ( $a['score'] != $b['score'] )
                return $a['score'] < $b['score'] ? 1 : -1;
            return strcmp( $a['locale'], $b['locale'] );
        } );

        $tiers = array();
        foreach ( self::TIERS as $tier )
            $tiers[$tier] = array( 'pages' => 0, 'entries' => 0, 'words' => 0, 'parts' => 0 );
        foreach ( $helpParts as $part )
        {
            $tiers[$part['tier']]['pages'] += $part['pages'];
            $tiers[$part['tier']]['entries'] += $part['entries'];
            $tiers[$part['tier']]['words'] += $part['words'];
            $tiers[$part['tier']]['parts']++;
        }
        $messages = 0;
        $words = 0;
        foreach ( $adminParts as $i => $part )
        {
            $messages += $part['messages'];
            $words += $part['words'];
            unset( $adminParts[$i]['keys'] );
        }
        $this->data = array(
            'admin' => array( 'parts' => $adminParts, 'messages' => $messages, 'words' => $words ),
            'extensions' => $extensions,
            'help' => array( 'parts' => $helpParts, 'tiers' => $tiers, 'directories' => array_keys( $directories ) ),
            'status' => $status,
            'untranslated' => $untranslated,
        );
        $this->data['queue'] = $this->queue();
        return $this->data;
    }

    /**
     * The waves in the order of the work, list of hash( id (<locale>/<work set>), locale, set, kind (admin, derived,
     * locale, extensions, setup, help), size (hash( messages, pages, entries, words, missing )), difficulty, phase ):
     *
     *  1  the priority group's catalogues below 100 %: the administration parts and the shipped extensions; Dari
     *  2  German: the help of daily use it has not translated yet
     *  3  the priority group's help of daily use: the setup of its help language, then part after part, one language
     *     after the other (each language gets a part before any gets the next)
     *  4  the new administration translations: the derived North Korean catalogue, then every language without one
     *     (new locales included) by speakers per point of difficulty; the ones in progress on a branch wait
     *  5  the shipped extension catalogues of every other translation below 100 %
     *  6  the help of daily use of every other translation, in the same way as phase 3, by speakers per point of difficulty
     *  7  the rest of the help of the priority group (German first), guides, reference and tables
     *  8  the rest of the help of every other translation
     *
     * @return array
     */
    public function queue()
    {
        $data = $this->data;
        $status = $data['status'];
        $queue = array();
        $add = function ( $phase, $locale, $set, $kind, array $size ) use ( &$queue )
        {
            $info = expI18nTranslationWaves::language( $locale );
            $queue[] = array( 'id' => $locale . '/' . $set, 'locale' => $locale, 'set' => $set, 'kind' => $kind, 'size' => $size + array(
                              'messages' => 0, 'pages' => 0, 'entries' => 0, 'words' => 0, 'missing' => 0 ),
                              'difficulty' => $info['difficulty'], 'phase' => $phase );
        };
        $adminParts = $data['admin']['parts'];
        $helpParts = $data['help']['parts'];
        $extensionsTotal = array_sum( $data['extensions'] );
        $translated = array_keys( $status );
        $catalogueWaves = function ( $phase, $locale ) use ( $status, $adminParts, $extensionsTotal, $add )
        {
            foreach ( $adminParts as $part )
            {
                $have = $status[$locale]['admin_parts'][$part['id']];
                if ( $have < 100 )
                    $add( $phase, $locale, $part['id'], 'admin', array( 'messages' => $part['messages'], 'words' => $part['words'],
                                                                        'missing' => (int)ceil( $part['messages'] * ( 100 - $have ) / 100 ) ) );
            }
        };
        $extensionWave = function ( $phase, $locale ) use ( $status, $extensionsTotal, $add )
        {
            if ( $extensionsTotal > 0 && $status[$locale]['extensions'] < 100 )
                $add( $phase, $locale, 'E', 'extensions', array( 'messages' => $extensionsTotal,
                                                                 'missing' => (int)ceil( $extensionsTotal * ( 100 - $status[$locale]['extensions'] ) / 100 ) ) );
        };
        $helpWave = function ( $phase, $locale, array $part ) use ( $status, $add )
        {
            $have = $status[$locale]['help_parts'][$part['id']];
            if ( $have >= 100 )
                return;
            $add( $phase, $locale, $part['id'], 'help', array( 'pages' => $part['pages'], 'entries' => $part['entries'], 'words' => $part['words'],
                                                               'missing' => (int)ceil( $part['words'] * ( 100 - $have ) / 100 ) ) );
        };
        $setupDone = array();
        $setupWave = function ( $phase, $locale ) use ( $status, $add, &$setupDone )
        {
            // once per language, before its first part of the help
            if ( $status[$locale]['directory'] === '' && !isset( $setupDone[$locale] ) )
                $add( $phase, $locale, 'S', 'setup', array() );
            $setupDone[$locale] = true;
        };
        $byScore = function ( array $locales )
        {
            usort( $locales, function ( $a, $b )
            {
                $x = expI18nTranslationWaves::language( $a )['score'];
                $y = expI18nTranslationWaves::language( $b )['score'];
                return $x == $y ? strcmp( $a, $b ) : ( $x < $y ? 1 : -1 );
            } );
            return $locales;
        };
        $priority = array_values( array_filter( self::PRIORITY, function ( $locale ) use ( $status ) { return isset( $status[$locale] ); } ) );
        $hasGerman = isset( $status[self::PRIORITY_GERMAN] );
        $roundRobin = function ( $phase, array $locales, array $tiers ) use ( $helpParts, $helpWave, $setupWave )
        {
            foreach ( $locales as $locale )
                $setupWave( $phase, $locale );
            foreach ( $helpParts as $part )
            {
                if ( !in_array( $part['tier'], $tiers, true ) )
                    continue;
                foreach ( $locales as $locale )
                    $helpWave( $phase, $locale, $part );
            }
        };

        // 1
        foreach ( array_merge( $hasGerman ? array( self::PRIORITY_GERMAN ) : array(), $priority ) as $locale )
        {
            $catalogueWaves( 1, $locale );
            $extensionWave( 1, $locale );
        }
        foreach ( $data['untranslated'] as $locale => $entry )
        {
            // the derived catalogue of the group is usable once made; its review waits for phase 4
            if ( isset( $entry['from'] ) && !empty( self::DERIVED[$locale]['priority'] ) )
                $add( 1, $locale, 'L', 'derived', array() );
        }
        // 2
        if ( $hasGerman )
        {
            foreach ( $helpParts as $part )
            {
                if ( $part['tier'] === 'daily' )
                    $helpWave( 2, self::PRIORITY_GERMAN, $part );
            }
        }
        // 3
        $roundRobin( 3, $priority, array( 'daily' ) );
        // 4
        foreach ( $data['untranslated'] as $locale => $entry )
        {
            if ( isset( $entry['from'] ) )
                $this->newCatalogueWaves( 4, $entry, $add, !empty( self::DERIVED[$locale]['priority'] ) );
        }
        foreach ( $data['untranslated'] as $locale => $entry )
        {
            if ( !isset( $entry['from'] ) && !$entry['in_progress'] )
                $this->newCatalogueWaves( 4, $entry, $add );
        }
        // 5, 6
        $others = $byScore( array_values( array_filter( $translated, function ( $locale ) use ( $priority )
        {
            return strpos( $locale, 'eng-' ) !== 0 && $locale !== expI18nTranslationWaves::PRIORITY_GERMAN && !in_array( $locale, $priority, true );
        } ) ) );
        foreach ( $others as $locale )
        {
            $catalogueWaves( 5, $locale );
            $extensionWave( 5, $locale );
        }
        $roundRobin( 6, $others, array( 'daily' ) );
        // 7, 8
        if ( $hasGerman )
        {
            foreach ( $helpParts as $part )
            {
                if ( $part['tier'] !== 'daily' )
                    $helpWave( 7, self::PRIORITY_GERMAN, $part );
            }
        }
        $roundRobin( 7, $priority, array( 'guides', 'reference', 'tables' ) );
        $roundRobin( 8, $others, array( 'guides', 'reference', 'tables' ) );
        foreach ( $queue as $i => $wave )
            $queue[$i]['number'] = $i + 1;
        return $queue;
    }

    /**
     * The waves of a new administration translation: its locale file when it has none, then every part of the catalogue
     * (for a derived catalogue: the review of each part against the language's glossary).
     *
     * @param int $phase
     * @param array $entry an untranslated entry
     * @param callable $add
     * @param bool $reviewOnly the locale wave is already in the queue
     */
    protected function newCatalogueWaves( $phase, array $entry, $add, $reviewOnly = false )
    {
        $locale = $entry['locale'];
        if ( !$reviewOnly && ( !empty( $entry['new'] ) || isset( $entry['from'] ) ) )
            $add( $phase, $locale, 'L', isset( $entry['from'] ) ? 'derived' : 'locale', array() );
        foreach ( $this->data['admin']['parts'] as $part )
            $add( $phase, $locale, $part['id'], isset( $entry['from'] ) ? 'review' : 'admin',
                  array( 'messages' => $part['messages'], 'words' => $part['words'], 'missing' => $part['messages'] ) );
    }

    /**
     * The figures the check compares: percentages exactly, sizes within TOLERANCE.
     *
     * @return array
     */
    public function figures()
    {
        $data = $this->data();
        $status = array();
        foreach ( $data['status'] as $code => $row )
            $status[$code] = array( $row['admin'], $row['extensions'], $row['daily'], $row['help'] );
        $sizes = array( 'messages' => $data['admin']['messages'], 'extensions' => array_sum( $data['extensions'] ), 'parts' => count( $data['help']['parts'] ) );
        foreach ( $data['help']['tiers'] as $tier => $figures )
        {
            $sizes[$tier . '_pages'] = $figures['pages'];
            $sizes[$tier . '_words'] = $figures['words'];
        }
        return array( 'status' => $status, 'sizes' => $sizes, 'waves' => count( $data['queue'] ),
                      'untranslated' => array_keys( $data['untranslated'] ) );
    }

