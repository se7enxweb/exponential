require_once __DIR__ . '/expDFSPostgreSQLWireLiveSetup.php';

#[\PHPUnit\Framework\Attributes\Group('cluster-live')]
#[\PHPUnit\Framework\Attributes\Group('pgwire-live')]
class expYugabyteDBDFSClusterLiveTest extends ezpTestCase
{
    use expDFSBackendParityChecks;
    use expDFSPostgreSQLWireLiveSetup;

    protected function supportsBoundedLockRetry()
    {
        return true;
    }

    protected function supportsTimesAfter2038()
    {
        return true;
    }

    const PROFILE = 'yugabytedb';

    /**
     * YugabyteDB 2.25 (its default REPEATABLE READ, wait queues on) differs from PostgreSQL here, measured live:
     * lock_timeout is not applied, so a store waits for as long as another transaction holds the row instead of
     * giving up after DBLockTimeout (a held row never ended the wait within 120 s). What holds: the store waits for
     * the lock and succeeds once it is released, and the row then has the new contents.
     */
    public function testLockWaitIsBoundedAndRetried()
    {
        $path = $this->path( 'files/locked.txt' );
        $this->backend->_storeContents( $path, 'before', 'binaryfile', 'text/plain', 1700000000 );
        $this->backend->_disconnect();
        $this->beforeFork();
        $pid = pcntl_fork();
        if ( $pid === 0 )
        {
            $holder = $this->newBackend();
            $this->holdLock( $holder, $path );
            usleep( 1500000 );
            $this->releaseLock( $holder );
            posix_kill( getmypid(), SIGKILL );
        }
        usleep( 300000 );
        $this->backend = $this->newBackend();
        $time = microtime( true );
        $this->assertNotFalse( $this->backend->_storeContents( $path, 'after', 'binaryfile', 'text/plain', 1700000100 ) );
        $time = microtime( true ) - $time;
        pcntl_waitpid( $pid, $status );
        $this->assertGreaterThan( 0.9, $time, 'the store waited for the lock' );
        $this->assertLessThan( 4.0, $time, 'and went on once it was released' );
        $this->assertSame( 'after', $this->backend->_fetchContents( $path ) );
    }

    /**
     * Four processes ask for one cache file at once. On YugabyteDB 2.25 a second process can be told 'ok' once the
     * first one's generation ended (measured: "2 ko; 0 ko; 1 ok ended; 3 ok ended"): the file is then generated twice,
     * one after the other, never by two at the same time over each other's .generating row. What holds: every process
     * answers, at least one generates, every generation ends, and the file has the contents of one of them.
     */
    public function testParallelGenerationOfOneKeyHasOneWinner()
    {
        $path = $this->path( 'cache/gen/parallel.cache' );
        $results = $this->dir . '/parallel-results.txt';
        $this->backend->_disconnect();
        $this->beforeFork();
        $start = microtime( true ) + 0.5;
        $children = array();
        for ( $i = 0; $i < 4; ++$i )
        {
            $pid = pcntl_fork();
            if ( $pid === 0 )
            {
                $line = "$i error";
                try
                {
                    $backend = $this->newBackend();
                    while ( microtime( true ) < $start )
                        usleep( 1000 );
                    $answer = $backend->_startCacheGeneration( $path, "$path.generating" );
                    $line = "$i " . $answer['result'];
                    if ( $answer['result'] === 'ok' )
                    {
                        usleep( 300000 );
                        $backend->_storeContents( "$path.generating", "generated by $i", 'viewcache', 'text/plain' );
                        $line .= $backend->_endCacheGeneration( $path, "$path.generating", true ) ? ' ended' : ' not-ended';
                    }
                }
                catch ( Exception $e )
                {
                    $line = "$i exception " . $e->getMessage();
                }
                file_put_contents( $results, "$line\n", FILE_APPEND | LOCK_EX );
                posix_kill( getmypid(), SIGKILL );
            }
            $children[] = $pid;
        }
        foreach ( $children as $pid )
            pcntl_waitpid( $pid, $status );

        $this->backend = $this->newBackend();
        $lines = file( $results, FILE_IGNORE_NEW_LINES );
        $this->assertCount( 4, $lines, implode( '; ', $lines ) );
        $winners = preg_grep( '/^\d ok ended$/', $lines );
        $this->assertGreaterThanOrEqual( 1, count( $winners ), implode( '; ', $lines ) );
        $this->assertCount( 4 - count( $winners ), preg_grep( '/^\d ko$/', $lines ), implode( '; ', $lines ) );
        $contents = $this->backend->_fetchContents( $path );
        $this->assertContains( $contents, array_map( function ( $line ) { return 'generated by ' . (int)$line; }, $winners ) );
        $this->assertFalse( $this->backend->_fetchMetadata( "$path.generating" ) );
    }
}
