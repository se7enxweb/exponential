<?php
/**
 * Which image aliases pre-generation after publishing makes ([AliasSettings] PreGenerateAliasList[] and
 * PreGenerateFormats), without a database:
 *
 *  IAP-01 - empty list (the default): the union of the related siteaccesses as it is; variants on by default
 *  IAP-02 - a list: only those aliases, each with the siteaccess that defines it; a siteaccess left without an
 *           alias is dropped; names trimmed and each once; the job's payload carries only the chosen aliases
 *  IAP-03 - unknown names: skipped, reported, and logged once per publication (event=queue result=unknown-alias);
 *           a list of unknown names only leaves nothing to make
 *  IAP-04 - variants on and off: the formats of the job, and which stored images need work (a missing variant counts
 *           only when variants are on, and only for an alias of the plan)
 *  IAP-05 - Setup > Image aliases offers both keys, checks the alias names and shows the choice on the dashboard
 *
 * Run: php vendor/bin/phpunit tests/tests/kernel/classes/imagealias/expImageAliasPreGenerateTest.php
 *
 * @copyright Copyright (C) 1998 - 2026 Exponential Foundation and 7x; All rights reserved.
 * @license GNU General Public License v2.0 (or any later version)
 * @package tests
 */

class expImageAliasPreGenerateTest extends PHPUnit\Framework\TestCase
{
    /** @var string */
    private $base;

    /** @var string */
    private $dir;

    /** @var string|false */
    private $cwd = false;

    /** The union pre-generation starts from: siteaccess => aliases (expImageAliasSettings::siteAccessAliasPlan()) */
    const UNION = array( 'admin' => array( 'small', 'large', 'reference' ), 'site' => array( 'listitem', 'i160' ) );

    public static function setUpBeforeClass(): void
    {
        // the cluster file handler (a variant's exists()) registers it on first use; done here, not inside a test
        eZExecution::registerShutdownHandler();
    }

    protected function setUp(): void
    {
        parent::setUp();
        $this->cwd = getcwd();
        chdir( dirname( __DIR__, 5 ) );
        $this->base = 'var/tmp/storage/images/exp_iap_' . getmypid() . '_' . mt_rand();
        $this->dir = $this->base . '/7-1-eng-GB';
        mkdir( $this->dir, 0700, true );
        expImageAliasLog::setDirectory( $this->base . '/log' );
    }

    protected function tearDown(): void
    {
        ezpINIHelper::restoreINISettings();
        expImageFormatConverter::setCapabilities( null );
        expImageAliasLog::setDirectory( null );
        foreach ( array( $this->dir, $this->base . '/log' ) as $dir )
        {
            foreach ( (array)glob( $dir . '/*' ) as $file )
                @unlink( $file );
            @rmdir( $dir );
        }
        @rmdir( $this->base );
        if ( $this->cwd !== false )
            chdir( $this->cwd );
        parent::tearDown();
    }

    /** The stored XML of an image attribute with $aliases made */
    private function xml( $original, array $aliases )
    {
        $out = '<?xml version="1.0" encoding="utf-8"?><ezimage serial_number="1" is_valid="1" filename="a.jpg" suffix="jpg" basename="a"'
             . ' dirpath="' . $this->dir . '" url="' . $original . '" original_filename="a.jpg" mime_type="image/jpeg" width="10" height="10"'
             . ' alternative_text="" alias_key="1293033771" timestamp="1">';
        foreach ( $aliases as $name )
            $out .= '<alias name="' . $name . '" filename="a_' . $name . '.jpg" suffix="jpg" dirpath="' . $this->dir . '" url="' . $this->dir . '/a_' . $name
                  . '.jpg" mime_type="image/jpeg" width="5" height="5" alias_key="1" timestamp="1" is_valid="1"/>';
        return $out . '</ezimage>';
    }

    /** @return array the unknown-alias lines of the test log */
    private function unknownLines()
    {
        return array_values( array_filter( expImageAliasLog::read( 100, 'queue' ), function ( $entry ) {
            return $entry['result'] === 'unknown-alias';
        } ) );
    }

    /** IAP-01 */
    public function testEmptyListKeepsTheUnion()
    {
        ezpINIHelper::setINISetting( 'image.ini', 'AliasSettings', 'PreGenerateAliasList', array() );
        $this->assertSame( array(), expImageAliasSettings::preGenerateAliasList() );
        $this->assertTrue( expImageAliasSettings::preGenerateFormatsEnabled(), 'variants are pre-generated by default' );
        $this->assertSame( array( 'plan' => self::UNION, 'unknown' => array() ), expImageAliasSettings::preGeneratePlan( self::UNION, array() ) );

        $plan = expImageAliasPublish::plan( 1, 1, self::UNION );
        $this->assertSame( self::UNION, $plan['plan'] );
        $this->assertSame( expImageAliasPublish::FORMATS, $plan['formats'] );
        $this->assertSame( array(), $this->unknownLines(), 'nothing logged' );

        // what ships in settings/image.ini: the empty list and the variants on
        $ini = file_get_contents( 'settings/image.ini' );
        $this->assertMatchesRegularExpression( '/^PreGenerateAliasList\[\]\s*$/m', $ini );
        $this->assertMatchesRegularExpression( '/^PreGenerateFormats=enabled\s*$/m', $ini );
    }

    /** IAP-02 */
    public function testAListNarrowsTheUnion()
    {
        ezpINIHelper::setINISetting( 'image.ini', 'AliasSettings', 'PreGenerateAliasList', array( ' large ', 'i160', '', 'large' ) );
        $this->assertSame( array( 'large', 'i160' ), expImageAliasSettings::preGenerateAliasList(), 'trimmed, each once, the order kept' );

        $plan = expImageAliasPublish::plan( 1, 1, self::UNION );
        $this->assertSame( array( 'admin' => array( 'large' ), 'site' => array( 'i160' ) ), $plan['plan'],
                           'each alias stays with the siteaccess whose image.ini makes it' );
        $this->assertSame( array(), $plan['unknown'] );

        // a siteaccess left without an alias is dropped
        $only = expImageAliasSettings::preGeneratePlan( self::UNION, array( 'listitem' ) );
        $this->assertSame( array( 'site' => array( 'listitem' ) ), $only['plan'] );

        // the queued job carries only the chosen aliases
        $payload = expImageAliasJob::generatePayload( array( 'items' => array( array( 7, 1, 'eng-GB' ) ), 'aliases' => $plan['plan'],
                                                             'formats' => $plan['formats'], 'origin' => 'publish' ) );
        $this->assertSame( array( 'admin' => array( 'large' ), 'site' => array( 'i160' ) ), $payload['aliases'] );
        $this->assertSame( array( 'webp', 'avif' ), $payload['formats'] );
        $this->assertNull( expImageAliasJob::generatePayloadError( $payload ) );

        // which images need work: only the chosen aliases count
        $this->assertFalse( expImageAliasPublish::needsWork( $this->xml( $this->dir . '/a.jpg', array( 'large', 'i160' ) ), $plan['plan'] ),
                            'small, reference and listitem are missing, but not chosen' );
        $this->assertTrue( expImageAliasPublish::needsWork( $this->xml( $this->dir . '/a.jpg', array( 'large' ) ), $plan['plan'] ) );
    }

    /** IAP-03 */
    public function testUnknownNamesAreSkippedAndLoggedOnce()
    {
        ezpINIHelper::setINISetting( 'image.ini', 'AliasSettings', 'PreGenerateAliasList', array( 'small', 'nosuch', 'original', 'nosuch' ) );
        $plan = expImageAliasPublish::plan( 59737, 2, self::UNION );
        $this->assertSame( array( 'admin' => array( 'small' ) ), $plan['plan'] );
        $this->assertSame( array( 'nosuch', 'original' ), $plan['unknown'] );
        $lines = $this->unknownLines();
        $this->assertCount( 1, $lines, 'one line per publication' );
        $this->assertSame( 'nosuch,original', $lines[0]['alias'] );
        $this->assertStringContainsString( 'origin=publish', $lines[0]['line'] );
        $this->assertStringContainsString( 'object=59737', $lines[0]['line'] );

        // only unknown names: nothing to make, so no image needs work
        ezpINIHelper::setINISetting( 'image.ini', 'AliasSettings', 'PreGenerateAliasList', array( 'nosuch' ) );
        $plan = expImageAliasPublish::plan( 59737, 3, self::UNION );
        $this->assertSame( array(), $plan['plan'] );
        $this->assertFalse( expImageAliasPublish::needsWork( $this->xml( $this->dir . '/a.jpg', array() ), $plan['plan'] ) );
        $this->assertCount( 2, $this->unknownLines() );
    }

    /** IAP-04 */
    public function testVariantsOnAndOff()
    {
        $this->assertSame( array( 'webp', 'avif' ), expImageAliasPublish::formats( true ) );
        $this->assertSame( array(), expImageAliasPublish::formats( false ) );
        ezpINIHelper::setINISetting( 'image.ini', 'AliasSettings', 'PreGenerateFormats', 'disabled' );
        $this->assertFalse( expImageAliasSettings::preGenerateFormatsEnabled() );
        $plan = expImageAliasPublish::plan( 1, 1, self::UNION );
        $this->assertSame( array(), $plan['formats'] );
        $payload = expImageAliasJob::generatePayload( array( 'items' => array( array( 7, 1, 'eng-GB' ) ), 'aliases' => $plan['plan'],
                                                             'formats' => $plan['formats'], 'origin' => 'publish' ) );
        $this->assertArrayNotHasKey( 'formats', $payload, 'the job makes no variant' );
        ezpINIHelper::setINISetting( 'image.ini', 'AliasSettings', 'PreGenerateFormats', 'enabled' );
        $this->assertTrue( expImageAliasSettings::preGenerateFormatsEnabled() );

        // a variant the alias block lists and a converter writes, missing
        $all = array( 'small', 'large', 'reference', 'listitem', 'i160' );
        ezpINIHelper::setINISetting( 'image.ini', 'small', 'Formats', array( 'webp' ) );
        expImageFormatConverter::setCapabilities( array( 'gd' => array( 'webp' ), 'imagick' => array(), 'imagemagick' => array() ) );
        $xml = $this->xml( $this->dir . '/a.jpg', $all );
        $this->assertTrue( expImageAliasPublish::needsWork( $xml, self::UNION, true ), 'variants on: the missing WebP is work' );
        $this->assertFalse( expImageAliasPublish::needsWork( $xml, self::UNION, false ), 'variants off: it is not' );
        $this->assertFalse( expImageAliasPublish::needsWork( $xml, array( 'admin' => array( 'large' ) ), true ),
                            'the variant of an alias outside the plan is not the job\'s work' );
        file_put_contents( $this->dir . '/a_small.jpg.webp', 'RIFF' );
        $this->assertFalse( expImageAliasPublish::needsWork( $xml, self::UNION, true ) );
    }

    /** IAP-05 */
    public function testSetupPageOffersAndShowsTheChoice()
    {
        $defs = expImageAliasAdmin::settingsDefinition();
        $this->assertSame( 'list', $defs['AliasSettings']['PreGenerateAliasList']['type'] );
        $this->assertSame( array(), $defs['AliasSettings']['PreGenerateAliasList']['default'] );
        $this->assertSame( 'enabled', $defs['AliasSettings']['PreGenerateFormats']['default'] );
        $list = expImageAliasAdmin::validateValue( $defs['AliasSettings']['PreGenerateAliasList'], "large\r\n\r\ni160\nlarge " );
        $this->assertTrue( $list['ok'] );
        $this->assertSame( array( 'large', 'i160' ), $list['value'] );
        $this->assertFalse( expImageAliasAdmin::validateValue( $defs['AliasSettings']['PreGenerateAliasList'], 'bad name' )['ok'] );
        $this->assertFalse( expImageAliasAdmin::validateValue( $defs['AliasSettings']['PreGenerateAliasList'], 'original' )['ok'] );
        $this->assertFalse( expImageAliasAdmin::validateValue( $defs['AliasSettings']['PreGenerateFormats'], 'yes' )['ok'] );

        foreach ( array( 'admin', 'admin4' ) as $design )
        {
            $row = file_get_contents( "design/$design/templates/setup/aliases_setting_row.tpl" );
            $this->assertStringContainsString( "{case match='PreGenerateAliasList'}", $row );
            $this->assertStringContainsString( "{case match='PreGenerateFormats'}", $row );
            $page = file_get_contents( "design/$design/templates/setup/aliases.tpl" );
            $this->assertStringContainsString( '$d.pre_generate_aliases', $page );
            $this->assertStringContainsString( '$d.pre_generate_formats', $page );
        }
        $source = file_get_contents( 'kernel/classes/imagealias/expimagealiasadmin.php' );
        $this->assertStringContainsString( "'pre_generate_aliases' => expImageAliasSettings::preGenerateAliasList()", $source );
    }
}
